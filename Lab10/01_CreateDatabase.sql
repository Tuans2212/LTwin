-- Script tao database EduManagerDB
USE master;
GO
DROP DATABASE IF EXISTS EduManagerDB;
GO
CREATE DATABASE EduManagerDB;
GO
USE EduManagerDB;
GO

-- 1. Tao bang KHOA
CREATE TABLE KHOA (
    MaKhoa VARCHAR(15) PRIMARY KEY,
    TenKhoa NVARCHAR(100) NOT NULL,
    SoDienThoai VARCHAR(15)
);

-- 2. Tao bang LOP
CREATE TABLE LOP (
    MaLop VARCHAR(15) PRIMARY KEY,
    TenLop NVARCHAR(100) NOT NULL,
    MaKhoa VARCHAR(15) NOT NULL,
    CONSTRAINT FK_Lop_Khoa FOREIGN KEY (MaKhoa) REFERENCES KHOA(MaKhoa)
);

-- 3. Tao bang SINHVIEN
CREATE TABLE SINHVIEN (
    MaSV VARCHAR(15) PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    NgaySinh DATE,
    GioiTinh NVARCHAR(10) NOT NULL,
    MaLop VARCHAR(15) NOT NULL,
    CONSTRAINT CK_GioiTinh CHECK (GioiTinh IN (N'Nam', N'Nữ')),
    CONSTRAINT FK_SV_Lop FOREIGN KEY (MaLop) REFERENCES LOP(MaLop)
);

-- 4. Tao bang MONHOC
CREATE TABLE MONHOC (
    MaMH VARCHAR(15) PRIMARY KEY,
    TenMH NVARCHAR(100) NOT NULL,
    SoTinChi INT NOT NULL,
    CONSTRAINT CK_TinChi CHECK (SoTinChi > 0)
);

-- 5. Tao bang KETQUA
CREATE TABLE KETQUA (
    MaSV VARCHAR(15) NOT NULL,
    MaMH VARCHAR(15) NOT NULL,
    Diem FLOAT NOT NULL,
    PRIMARY KEY (MaSV, MaMH),
    CONSTRAINT FK_KQ_SV FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV),
    CONSTRAINT FK_KQ_MH FOREIGN KEY (MaMH) REFERENCES MONHOC(MaMH),
    CONSTRAINT CK_Diem CHECK (Diem >= 0 AND Diem <= 10)
);

-- 6. Tao bang TAIKHOAN
CREATE TABLE TAIKHOAN (
    TenDangNhap VARCHAR(50) PRIMARY KEY,
    MatKhau VARCHAR(50) NOT NULL,
    HoTen NVARCHAR(100) NOT NULL,
    VaiTro VARCHAR(20) DEFAULT 'User'
);
